-- Students Table
CREATE TABLE students (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(25),
    department VARCHAR2(25),
    year VARCHAR2(10),
    email VARCHAR2(25),
    phone VARCHAR2(15)
);

-- Courses Table
CREATE TABLE courses (
    course_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_name VARCHAR2(50),
    department VARCHAR2(25)
);

-- Enrollments Table
CREATE TABLE enrollments (
    enrollment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER REFERENCES students(student_id),
    course_id NUMBER REFERENCES courses(course_id)
);

-- Attendance Table
CREATE TABLE attendance (
    attendance_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    student_id      NUMBER NOT NULL,
    course_id       NUMBER NOT NULL,
    attendance_date DATE NOT NULL,
    status          VARCHAR2(10) CHECK (status IN ('Present', 'Absent')),
    CONSTRAINT fk_student FOREIGN KEY (student_id) REFERENCES students(student_id),
    CONSTRAINT fk_course  FOREIGN KEY (course_id) REFERENCES courses(course_id),
    CONSTRAINT uc_attendance UNIQUE (student_id, course_id, attendance_date)
);
